/**
 * Custom fields.
 *
 * Board-scoped definitions, card-scoped values, and the value is always text —
 * the field's `type` decides how it is parsed and rendered. One column beats a
 * sparse table of typed columns that is mostly null whatever anyone configures.
 */
export const customField = pgTable(
  "custom_field",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    boardId: uuid("board_id")
      .notNull()
      .references(() => board.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    type: text("type").$type<"text" | "number" | "date" | "select" | "checkbox">().notNull(),
    /** Choices for a select field; empty for every other type. */
    options: jsonb("options").$type<string[]>().notNull().default([]),
    position: text("position").notNull(),
  },
  (t) => [index("custom_field_board_idx").on(t.boardId, t.position)],
);

export const customFieldValue = pgTable(
  "custom_field_value",
  {
    cardId: uuid("card_id")
      .notNull()
      .references(() => card.id, { onDelete: "cascade" }),
    fieldId: uuid("field_id")
      .notNull()
      .references(() => customField.id, { onDelete: "cascade" }),
    value: text("value").notNull(),
  },
  (t) => [primaryKey({ columns: [t.cardId, t.fieldId] })],
);

export type CustomFieldRow = typeof customField.$inferSelect;


/* ---------------------------------------------------------------- M4 tables */

/**
 * API tokens.
 *
 * Only the hash is stored, so a database dump does not hand over anyone's
 * access — the plaintext is shown once, at creation, and never again.
 */
export const apiToken = pgTable(
  "api_token",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    /** SHA-256 of the token. Indexed because every API call looks it up. */
    tokenHash: text("token_hash").notNull(),
    lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
    expiresAt: timestamp("expires_at", { withTimezone: true }),
    createdAt: now(),
  },
  (t) => [
    uniqueIndex("api_token_hash_uq").on(t.tokenHash),
    index("api_token_user_idx").on(t.userId),
  ],
);

/** Outbound webhooks. One row per endpoint per board. */
export const webhook = pgTable(
  "webhook",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    boardId: uuid("board_id")
      .notNull()
      .references(() => board.id, { onDelete: "cascade" }),
    url: text("url").notNull(),
    /** Signs the payload so the receiver can prove it came from here. */
    secret: text("secret").notNull(),
    active: boolean("active").notNull().default(true),
    /** Last delivery outcome, so a broken endpoint is visible without logs. */
    lastStatus: integer("last_status"),
    lastError: text("last_error"),
    lastFiredAt: timestamp("last_fired_at", { withTimezone: true }),
    createdAt: now(),
  },
  (t) => [index("webhook_board_idx").on(t.boardId)],
);

/**
 * Automation rules — the Butler equivalent, free and open.
 *
 * Trigger and actions are jsonb because their shape is a discriminated union
 * that will grow; the alternative is a column per action type, mostly null.
 */
export const rule = pgTable(
  "rule",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    boardId: uuid("board_id")
      .notNull()
      .references(() => board.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    enabled: boolean("enabled").notNull().default(true),
    trigger: jsonb("trigger").notNull(),
    actions: jsonb("actions").notNull(),
    /** For the rule list: has this ever actually done anything? */
    lastFiredAt: timestamp("last_fired_at", { withTimezone: true }),
    fireCount: integer("fire_count").notNull().default(0),
    createdAt: now(),
  },
  (t) => [index("rule_board_idx").on(t.boardId)],
);

