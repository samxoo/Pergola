/**
 * Who can see and change a board.
 *
 * Deliberately board-level rather than a full organisation model: a self-hosted
 * team shares boards, not an org chart. Organisations can be layered on later
 * without moving anything here.
 */
export const boardMember = pgTable(
  "board_member",
  {
    boardId: uuid("board_id")
      .notNull()
      .references(() => board.id, { onDelete: "cascade" }),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    /** admin edits the board itself, member edits cards, observer reads. */
    role: text("role").$type<"admin" | "member" | "observer">().notNull().default("member"),
    createdAt: now(),
  },
  (t) => [
    primaryKey({ columns: [t.boardId, t.userId] }),
    index("board_member_user_idx").on(t.userId),
  ],
);

