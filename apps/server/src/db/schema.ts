/**
 * Invitations.
 *
 * A fresh self-hosted instance has no mail server, so the link is handed to the
 * admin to pass on however they like. Only the hash is stored, exactly as with
 * API tokens: a database dump must not be a set of working invitations.
 */
export const invite = pgTable(
  "invite",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    email: text("email").notNull(),
    role: text("role").$type<"owner" | "admin" | "member">().notNull().default("member"),
    tokenHash: text("token_hash").notNull(),
    invitedBy: text("invited_by").references(() => user.id, { onDelete: "set null" }),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    acceptedAt: timestamp("accepted_at", { withTimezone: true }),
    createdAt: now(),
  },
  (t) => [
    uniqueIndex("invite_token_uq").on(t.tokenHash),
    index("invite_email_idx").on(t.email),
  ],
);

/**
 * Instance settings.
 *
 * Key/value rather than columns, so an owner can change how people get in
 * without an admin editing an env file and restarting the box.
 */
export const setting = pgTable("setting", {
  key: text("key").primaryKey(),
  value: jsonb("value").notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

