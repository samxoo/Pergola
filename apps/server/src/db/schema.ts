const now = () =>
  timestamp("created_at", { withTimezone: true }).notNull().defaultNow();

/** Postgres full-text search vector. Drizzle has no built-in for it. */
const tsvector = customType<{ data: string; driverData: string }>({
  dataType: () => "tsvector",
});

export const board = pgTable("board", {
  id: uuid("id").primaryKey().defaultRandom(),
  title: text("title").notNull(),
  /** "public" serves a read-only snapshot to anyone with the link. */
  visibility: text("visibility").$type<"private" | "public">().notNull().default("private"),
  /**
   * Per-board monotonic mutation counter. Every write bumps it inside the same
   * transaction that applies the change, which is what gives clients a cursor to
   * sync from and what serialises concurrent writers to one board (and only to
   * that board — different boards never contend).
   */
  seq: bigint("seq", { mode: "number" }).notNull().default(0),
  /** Board-scoped card numbering, so cards can be named out loud: PRG-142. */
  cardSeq: integer("card_seq").notNull().default(0),
  createdAt: now(),
});

export const list = pgTable(
  "list",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    boardId: uuid("board_id")
      .notNull()
      .references(() => board.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    /** Fractional index. See packages/shared/src/order.ts. */
    position: text("position").notNull(),
    /** Null means unlimited. The column turns amber when cards exceed it. */
    wipLimit: integer("wip_limit"),
    createdAt: now(),
  },
  (t) => [index("list_board_pos_idx").on(t.boardId, t.position)],
);

export const card = pgTable(
  "card",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    boardId: uuid("board_id")
      .notNull()
      .references(() => board.id, { onDelete: "cascade" }),
    listId: uuid("list_id")
      .notNull()
      .references(() => list.id, { onDelete: "cascade" }),
    position: text("position").notNull(),
    number: integer("number").notNull(),
    title: text("title").notNull(),
    descMd: text("desc_md"),
    dueAt: timestamp("due_at", { withTimezone: true }),
    startAt: timestamp("start_at", { withTimezone: true }),
    /** Trello's card cover, reduced to what people actually use: a colour. */
    coverColor: text("cover_color"),
    archivedAt: timestamp("archived_at", { withTimezone: true }),
    createdAt: now(),
    /*
     * Generated by Postgres on write, so the index can never drift from the text
     * it indexes — no trigger to maintain, no reindex job to forget. Title
     * outranks description, which is why they carry different weights.
     */
    search: tsvector("search").generatedAlwaysAs(
      sql`setweight(to_tsvector('simple', coalesce(title, '')), 'A') || setweight(to_tsvector('simple', coalesce(desc_md, '')), 'B')`,
    ),
  },
  (t) => [
    // The board's hot path: "give me one list, in order".
    index("card_list_pos_idx").on(t.listId, t.position),
    uniqueIndex("card_board_number_uq").on(t.boardId, t.number),
    index("card_search_idx").using("gin", t.search),
  ],
);

/**
 * The mutation log — the whole synchronisation layer.
 *
 * Real-time sync, reconnect, undo, the activity feed, the audit trail and
 * offline replay are all reads of this one table. There is no second write path.
 */
export const mutation = pgTable(
  "mutation",
  {
    /** Client-generated. Doubles as the idempotency key for retries and replay. */
    id: uuid("id").primaryKey(),
    boardId: uuid("board_id")
      .notNull()
      .references(() => board.id, { onDelete: "cascade" }),
    seq: bigint("seq", { mode: "number" }).notNull(),
    // Null only for mutations written before accounts existed, and for anything
    // the system does on its own behalf.
    actorId: text("actor_id").references(() => user.id, { onDelete: "set null" }),
    kind: text("kind").$type<MutationKind>().notNull(),
    payload: jsonb("payload").$type<MutationBody>().notNull(),
    /** The mutation that undoes this one. null => not undoable. */
    inverse: jsonb("inverse").$type<MutationBody | null>(),
    /**
     * Set when an automation rule produced this, rather than a person acting
     * directly. Encoding it in actor_id instead would break its foreign key —
     * and this way the activity feed can name the rule that did it.
     */
    ruleId: uuid("rule_id"),
    createdAt: now(),
  },
  (t) => [
    uniqueIndex("mutation_board_seq_uq").on(t.boardId, t.seq),
    index("mutation_feed_idx").on(t.boardId, sql`created_at DESC`),
  ],
);

export type BoardRow = typeof board.$inferSelect;
export type ListRow = typeof list.$inferSelect;
export type CardRow = typeof card.$inferSelect;
export type MutationRow = typeof mutation.$inferSelect;


